export function samplePercent(part: number, whole: number): number {
  return whole > 0 ? Math.round((part / whole) * 100) : 0;
}

/** Only a signed-in demo identity generated by randomUUID can view this page. */
export function isDemoSession(userId: unknown): boolean {
  return typeof userId === "string" &&
    /^demo:[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(userId);
}
